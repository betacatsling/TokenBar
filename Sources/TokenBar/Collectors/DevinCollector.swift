import Foundation
import SQLite3

/// Devin CLI stores history in SQLite, not JSONL:
/// `~/.local/share/devin/cli/sessions.db`.
///
/// Relevant shape:
///   sessions(id, model, backend_type, ...)
///   message_nodes(row_id, session_id, node_id, parent_node_id, chat_message,
///                 created_at, metadata)
///
/// `chat_message` is a JSON blob whose `metadata.metrics` holds the per-call
/// usage. The CLI is frequently running while we read, so the database is opened
/// with the read-only URI flag — never `sqlite3_open` on the plain path, which
/// would allow WAL recovery to touch the file.
///
/// ## Why rows are de-duplicated by `message_id`
///
/// `message_nodes` is a DAG, not a log. Each turn re-materialises the whole
/// conversation chain as fresh nodes, so one assistant message is stored once
/// per turn that followed it — same `message_id`, same `created_at`, same
/// `metadata.metrics`, new `node_id`. Counting per row therefore bills a single
/// API call up to seven times.
///
/// Measured over this machine's 6,265 rows: 1,315 of 1,340 usage-bearing
/// `message_id`s appear more than once (group sizes 2–7), and in **every one of
/// those 1,315 groups the token counts are byte-identical** — there is no case
/// where siblings disagree and a "which one is real" judgement would be needed.
/// Summing rows gives 249,440,445 tokens; counting each `message_id` once gives
/// **100,388,678**. The naive figure was a **2.485×** overcount.
///
/// `metadata.request_id` identifies the underlying API request — tokscale keys
/// on it rather than `message_id` because re-materialised copies share it.
/// Locally the two are in perfect 1:1 correspondence across 9,328 usage rows,
/// so either key dedups identically here; `request_id` is preferred with
/// `message_id` as fallback for schemas that lack it.
///
/// The key is still scoped by session: an id reused across two sessions would
/// otherwise silently delete a real call's usage.
///
/// ## Why the model comes from `metadata.generation_model`
///
/// `sessions.model` is the session's *current* setting, not what served any
/// given call. Switching model mid-session retroactively re-labels every earlier
/// call in that session, and a session whose model was never explicitly set
/// stores `''` — which this collector used to report as `unknown`.
///
/// `metadata.generation_model`, inside the message blob, records what actually
/// generated *that* message. Measured: it is present on **100%** of
/// usage-bearing rows on both machines (1,342 local, 6,208 on server1), so there
/// is no coverage cost to preferring it.
///
/// It also disagrees with the session column often — 190 of 1,342 rows locally
/// and **3,354 of 6,208 (54%) on server1**:
///
///   * server1 had two sessions with `model = ''` accounting for
///     **287,782,189 tokens** (0.65% of everything the app tracks) landing in an
///     `unknown` bucket. Every one of those rows carries a `generation_model` —
///     they are `swe-2-high` (190,496,451), `swe-2-max` (97,426,112) and
///     `compactor` (1,051,855). The blobs corroborate it independently: those
///     sessions' system prompts read *"You are powered by SWE-2 High/Max"*.
///   * locally, one `swe-2-max` session contains 15,229,304 tokens actually
///     generated by `swe-2-high`.
///
/// `compactor` is Devin's context-compaction model, which the session column can
/// never name; it has no published price and is reported unpriced rather than
/// folded into swe-2.
///
/// Note the two `created_at` columns disagree: `sessions.created_at` is not a
/// usable epoch (interpreting it as milliseconds yields 1970), while
/// `message_nodes.created_at` is a plain seconds-since-epoch value.
///
/// ## Why the day comes from `metadata.created_at`
///
/// `message_nodes.created_at` is when the *row* was written, and because each
/// turn re-materialises the whole chain, a copy's row timestamp is the time of
/// the turn that copied it — not of the call. Measured locally, the row stamp
/// runs a median of 80 minutes and up to 24.7 hours later than the generation.
///
/// `metadata.created_at`, inside the blob, is when the message was generated. It
/// is present on **100%** of usage-bearing rows on both machines, and — the
/// property that matters — it is **identical across every copy of a message**
/// (0 of 30 local and 0 of 1,580 server1 duplicate groups disagree), whereas the
/// row stamp differs across copies in **every** one of those groups. Keying the
/// day off the blob therefore makes attribution independent of which copy
/// de-duplication happens to keep; keying it off the row makes the daily chart
/// depend on scan order.
///
/// Measured impact: **5,751,125 tokens (5.7%) locally and 22,653,826 (3.7%) on
/// server1** were attributed to the wrong day. Totals are unaffected — this only
/// moves usage between days — but it is what the trend chart and "今日" read.
struct DevinCollector: Collector {
    let cli: CLIKind = .devin
    let origin: Origin = .local
    var dbPath: String {
        let env = ProcessInfo.processInfo.environment
        if let xdg = env["XDG_DATA_HOME"], !xdg.isEmpty {
            return xdg + "/devin/cli/sessions.db"
        }
        return home + "/.local/share/devin/cli/sessions.db"
    }

    func discoverPaths() -> [String] {
        FileManager.default.fileExists(atPath: dbPath) ? [dbPath] : []
    }

    func collect(cache: ScanCache) -> [UsageBucket] {
        guard FileManager.default.fileExists(atPath: dbPath)
                || cache.retainedPaths(under: (dbPath as NSString).deletingLastPathComponent).contains(dbPath) else { return [] }
        // The DB runs in WAL mode, so committed rows live in `-wal` until a
        // checkpoint folds them into the main file. Keying freshness on the `.db`
        // alone therefore serves stale totals — measured here as rows changing
        // while the main file's size and mtime both sat still. Fold the sidecars
        // into the cache key so any write invalidates the memo.
        return cache.buckets(for: dbPath, sidecars: Self.sidecarPaths(for: dbPath)) { _ in
            Self.scan(dbPath: dbPath, origin: origin)
        }
    }

    /// Files SQLite may write without touching the main database file.
    static func sidecarPaths(for dbPath: String) -> [String] {
        [dbPath + "-wal", dbPath + "-shm", dbPath + "-journal"]
    }

    /// Collapse swe-2's effort tiers into the one model they are.
    ///
    /// `swe-2-high` and `swe-2-max` differ in thinking effort, not in weights —
    /// the same model asked to reason harder. Reporting them as two models splits
    /// one model's usage across two rows and two share bars for a distinction
    /// that is a setting, not an identity.
    ///
    /// Deliberately scoped to the `swe-2-` prefix rather than generalised into a
    /// "strip a trailing `-high`/`-max`" rule: `gpt-5.1-codex-max` is its own
    /// model with its own catalog price, so a generic rule would merge genuinely
    /// distinct models and price them wrong.
    ///
    /// Every swe-2 variant observed on either machine is an effort tier, so a new
    /// suffix is assumed to be one too; a genuinely different model would be
    /// swe-3. The tiers price identically here (both inferred from kimi-k3), so
    /// merging moves no money — only rows.
    static func canonicalModel(_ name: String) -> String {
        name.lowercased().hasPrefix("swe-2-") ? "swe-2" : name
    }

    static func scan(dbPath: String, origin: Origin) -> [UsageBucket] {
        var db: OpaquePointer?
        // Read-only + immutable-safe: the CLI may hold the write lock.
        var components = URLComponents(url: URL(fileURLWithPath: dbPath), resolvingAgainstBaseURL: false)!
        components.queryItems = [URLQueryItem(name: "mode", value: "ro")]
        let uri = components.string!
        guard sqlite3_open_v2(uri, &db, SQLITE_OPEN_READONLY | SQLITE_OPEN_URI, nil) == SQLITE_OK,
              let db else { if let db { sqlite3_close(db) }; return [] }
        defer { sqlite3_close(db) }

        let sql = """
            SELECT s.model, m.chat_message, m.created_at, m.session_id
            FROM message_nodes m
            JOIN sessions s ON s.id = m.session_id
            ORDER BY m.row_id
            """
        var stmt: OpaquePointer?
        guard sqlite3_prepare_v2(db, sql, -1, &stmt, nil) == SQLITE_OK, let stmt else { return [] }
        defer { sqlite3_finalize(stmt) }

        var buckets: [UsageBucket] = []
        // Keyed by (session, message_id): the same assistant message is stored
        // once per subsequent turn, so only its first appearance is counted.
        var seen = Set<String>()

        while sqlite3_step(stmt) == SQLITE_ROW {
            // Drain per row; see ClaudeCodeCollector for why this matters to RSS.
            autoreleasepool {
                let sessionModel = columnText(stmt, 0) ?? ""
                guard let json = columnText(stmt, 1),
                      let data = json.data(using: .utf8),
                      let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any]
                else { return }

                // Only assistant rows carry real usage — no usage-bearing
                // non-assistant row has been observed, but filter anyway so a
                // schema change can't bill user bookkeeping as model traffic.
                guard (obj["role"] as? String ?? "assistant") == "assistant",
                      let metadata = obj["metadata"] as? [String: Any]
                else { return }

                let metrics = metadata["metrics"] as? [String: Any]
                var counts = TokenCounts(
                    input: intValue(metrics?["input_tokens"]),
                    output: intValue(metrics?["output_tokens"]),
                    cacheRead: intValue(metrics?["cache_read_tokens"]),
                    cacheWrite: intValue(metrics?["cache_creation_tokens"]),
                    cacheWrite1h: intValue(metrics?["cache_creation_1h_tokens"])
                )
                // Some schemas report `num_tokens` when no metrics block is
                // written; fold it into output rather than dropping the row.
                let numTokens = intValue(metadata["num_tokens"])
                if counts.total == 0, numTokens > 0 {
                    counts = TokenCounts(output: numTokens)
                }
                guard counts.total > 0 else { return }

                // `request_id` identifies the underlying API request; copies of
                // a re-materialised node share it. `message_id` is the fallback
                // for records written before the field existed, and a row with
                // neither counts once — dropping it would lose real usage.
                let requestID = (metadata["request_id"] as? String).flatMap { $0.isEmpty ? nil : $0 }
                let messageID = (obj["message_id"] as? String).flatMap { $0.isEmpty ? nil : $0 }
                if let dedupID = requestID ?? messageID {
                    let session = columnText(stmt, 3) ?? ""
                    guard seen.insert("\(session)\u{1}\(dedupID)").inserted else { return }
                }

                // What served *this* call, falling back to the session's setting
                // only if the per-message field is missing (never observed).
                // `adaptive` is a router alias, not a model — treat as unknown.
                let served = (metadata["generation_model"] as? String).flatMap { $0.isEmpty ? nil : $0 }
                    ?? (sessionModel.isEmpty || sessionModel == "adaptive" ? "unknown" : sessionModel)
                let model = Self.canonicalModel(served)

                // When the call happened, not when this copy of it was written.
                // Falls back to the row stamp only if the blob field is missing
                // or unparseable (never observed on either machine).
                let day = (metadata["created_at"] as? String)
                    .flatMap { DayFormatter.day(fromISO: $0) }
                    ?? DayFormatter.day(fromUnixSeconds: sqlite3_column_double(stmt, 2))

                var event = UsageEventRecord(rid: requestID ?? messageID ?? UUID().uuidString,
                                             model: model, day: day, tokens: counts)
                event.applyMetadata([metrics ?? [:], metadata])
                buckets.append(event.bucket(origin: origin, cli: .devin))
            }
        }

        return mergeBuckets(buckets)
    }

    private static func columnText(_ stmt: OpaquePointer, _ index: Int32) -> String? {
        guard let cstr = sqlite3_column_text(stmt, index) else { return nil }
        return String(cString: cstr)
    }
}
